/**
 * The mark for a service row, or null when there is none to draw.
 *
 * Takes the whole row rather than the key, because a System Admin may add a
 * service the seeded set does not name: that row has no `serviceKey`, so it
 * gets a monogram built from its own name instead of nothing at all.
 */
export function markFor(service: {
  serviceKey?: string;
  name: string;
}): ServiceMark {
  const known = service.serviceKey
    ? SERVICE_MARKS[service.serviceKey]
    : undefined;
  if (known) return known;
  return {
    path: null,
    color: null,
    monogram: monogramFrom(service.name),
    label: service.name,
  };
}

/** Up to two initials from a service name, for a row with no published mark. */
function monogramFrom(name: string): string {
  const words = name
    .split(/[^A-Za-z0-9]+/)
    .filter((word) => word.length > 0)
    .slice(0, 2);
  if (words.length === 0) return "?";
  return words.map((word) => word[0]!.toUpperCase()).join("");
}
