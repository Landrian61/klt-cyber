/**
 * Brand marks for the cost register's service cards (spec 0011).
 *
 * Every mark here is the vendor's own logo, used to identify that vendor and
 * nothing else. They are third party trademarks rather than part of "Kingdom
 * Radiant", which is why this is the one file in the portal that carries raw
 * hex literals: a brand colour is not ours to tokenise, and forcing these into
 * the palette would both misrepresent the brands and pollute the design
 * system. Nothing outside `ServiceLogo` reads this file.
 *
 * Path data is Simple Icons' (CC0), copied in rather than fetched, so the page
 * renders identically offline and makes no third party request from inside the
 * church's admin portal.
 *
 * A service with no published mark carries a monogram instead, drawn from the
 * design system's own surface tokens — inventing a brand colour for a vendor
 * whose logo we do not have would be a quiet lie about their identity.
 */

